LBL_PACK = """# 3x3 还原方法：入门分层法（LBL）

## 关键朝向约定
本平台中心块固定、没有整体旋转（已用代码核验）：U 面中心 white，D 面中心 yellow，
F 绿、B 蓝、R 红、L 橙。
因此本方法规定：先把黄色做在 D 面（第一层在底部），最后在 U 面做白色（最后一层在顶部）。
这样所有"最后一层"公式都可以原样在 U 面使用，不需要整体转动。
（颜色本身不影响方法，但不要中途改；即使 D 面暂时被破坏，也仍用黄色，不要换成当前 D 面出现最多的颜色。）

## 记号
R/L/U/D/F/B：该面顺时针 90°（从该面外侧看）；' 逆时针 90°；2 转 180°。
每个面的矩阵按"从该面外侧看"排列：行从上到下、列从左到右；
因此侧面的第 3 行（最下一行）贴着 D 面，第 1 行贴着 U 面。

## 总览与预算
共 8 个阶段，典型 85–110 步。平台每轮会把当前局面直接放进 user message，
每轮开头直接读取它，不需要额外 get_state；每完成一个阶段、切换前可 get_state 核对一次判据。
严禁跨阶段"顺手多转几下"，那会破坏已完成部分。

## 阶段 1：D 面十字（4 条含黄色棱块归位）
目标：D 面中心的黄色 + 4 个黄色棱贴纸组成十字，且每条棱的另一色与所在侧面中心一致。
做法：
- 在 U 层找一个含黄色的棱块，看它另一个颜色，把它转到"同色中心块所在的那一面"的正上方，
  再转该面 180° 把它放下去。
- 如果棱块在 D 层但侧面颜色错，先转回 U 层再重做，不要硬掰。
完成判据：D 面 5 格全黄（中心 + 4 条棱），且 R/F/L/B 每面第 3 行中间那一格与中心同色。

## 阶段 2：D 层四个角块（完成第一层）
目标：D 面 9 格全黄，且四个侧面的最下一排两个贴纸都与中心同色。
做法：把目标角块转到它该去的槽位正上方，看黄色贴在哪个面：
  - 黄色在 R 面 → R U R'
  - 黄色在 F 面 → F' U' F
  - 黄色在 U 面 → R2 U R2 U' R2
（以上是"前右槽"的写法；其它槽位先用 U 层把角块转到前右槽上方再套用。）
完成判据：D 面全黄 + 每侧最下排两格与中心同色。

## 阶段 3：第二层四个棱块
目标：四个侧面的中间一排（第 2 行）两个贴纸都与中心同色。
做法：在 U 层找不含白色的棱块，把它转到"目标槽的前/右上方"，然后：
  - 插入前右槽：U R U' R' U' F' U F
  - 插入前左槽：U' L' U L U F U' F'
如果棱块已经卡在槽里但方向反了，用同一条公式把它先顶到 U 层，再重新插入。
完成判据：四个侧面第 2 行全部与中心同色。

## 阶段 4：U 面十字（只要求 U 面棱贴纸同色）
完成判据：U 面中心 + 4 个 U 面棱贴纸都是白色（角块先不管）。
公式：F R U R' U' F'（每次做完重新看图案，不要连做）
  - 只有中心是白 → 做一次，得到"一字"或"L"
  - 一条白边（一字） → 把一字横放（左右方向），做一次
  - L 形 → 把 L 放在左上角，做一次
本公式不碰 D 层，第一层始终安全。

## 阶段 5：U 层棱块归位
完成判据：U 面 4 条棱的两个贴纸都与所在侧面中心同色。
公式（保留 UB 位置的棱不动，其余三条棱循环）：
  Ua   : R U' R U R U R U' R' U' R2
  Ua 逆: R2 U R U R' U' R' U' R' U R'
先数有几条棱的侧面颜色与中心不符：只有恰好 3 条时才用 Ua / Ua逆；不是 3 条就先回到 U 层归位再重数。
本公式不动角块，所以放在角块阶段之前。

## 阶段 6：U 层角块定向（U 面全白）
完成判据：U 面 9 格全白。
公式：
  Sune      : R U R' U R U2 R'
  Anti-Sune : R U2 R' U' R U' R'
每做一次就看 user message 里最新的 U 面（必要时 get_state 复核）；白色角贴纸变多就继续，没变就换另一条或先做一次 U 调整。
这两条公式会改变 U 层角块的位置、但不动已经归位的 U 层棱块，所以不会毁掉阶段 5。

## 阶段 7：U 层角块归位
完成判据：六面各自同色。
公式（角三循环，保留 UFR 位置的角不动，其余三个角循环）：
  U R U' L' U R' U' L
做两次等于反向循环；也可以直接用逆公式 L' U R U' L U R' U'。
前提：只在"U 面已经全白"时使用；如果用完 U 面不再全白，说明时机错了，先回到阶段 6。

## 阶段 8：收尾
- 若只剩 U 层整体转动错位，做 U / U' / U2。
- 最后 check_solved。

## 常见错步与纠正
1. 破坏上一阶段 → 不要就地修补，回到该阶段起点按判据重做。
2. 公式做完没有变化 → 大概率是朝向错了（该保留的块不在指定位置），先做 U 调整再套公式。
3. 第二层棱块来回摆动 → 说明目标槽判断错，先把棱块退回 U 层，重新对齐中心色再插。
4. 步数吃紧 → 优先减少阶段 3、4 的重试次数；阶段 1、2 不要为了"好看"多转。
5. 连续两轮工具调用局面完全回到同一状态 → 立即换思路，不要重复同一条公式。
"""

PACKS: dict[str, str] = {
    "ortega": ORTEGA_PACK,
    "lbl": LBL_PACK,
}


def pack_for(skill: str) -> str | None:
    """返回 skill 对应的 pack 文本；none/未知返回 None。"""
    if skill == SKILL_NONE:
        return None
    return PACKS.get(skill)


def cube_mismatch_error(skill: str, cube: str) -> str | None:
    """skill 与题集阶数不符时返回可直接展示的错误文案。"""
    expected = SKILL_CUBE.get(skill)
    if expected is None:
        return None
    if cube != expected:
        return (
            f"skill={skill} 只适用于 {expected} 题集，"
            f"当前 benchmark 是 {cube}"
        )
    return None
